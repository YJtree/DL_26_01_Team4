import pandas as pd

# ==================================================
# 1. 장소별 라벨링 결과 CSV 불러오기
# ==================================================
# 이 파일은 나중에 KcELECTRA 모델이 장소별 대표 라벨을 예측한 결과라고 가정합니다.
# 필요한 컬럼:
# city, place_name, place, top_label

df = pd.read_csv("final_travel_database.csv")


# ==================================================
# 2. 라벨명을 자연스러운 분위기 문장으로 변환하기 위한 딕셔너리
# ==================================================
# top_label 값이 그대로 들어가면 문장이 어색할 수 있으므로,
# 사람이 읽기 쉬운 설명 문구로 바꿔줍니다.

label_phrases = {
    "1번 (고즈넉/사색)": "고즈넉하고 사색적인 분위기",
    "2번 (레트로/빈티지)": "전통적이고 레트로한 빈티지 감성",
    "3번 (로컬/현지인)": "현지 분위기가 느껴지는 로컬 감성",
    "4번 (청량/애니메이션/바다)": "청량한 바다와 애니메이션 같은 감성",
    "5번 (아기자기/소박)": "아기자기하고 소박한 감성"
}


# ==================================================
# 3. 라벨별 추천 대상 문장
# ==================================================
# 각 라벨이 어떤 사용자의 취향과 연결되는지 설명하기 위한 문장입니다.

target_phrases = {
    "1번 (고즈넉/사색)": "조용히 산책하며 차분한 분위기를 느끼고 싶은 사용자",
    "2번 (레트로/빈티지)": "전통적인 거리와 오래된 감성을 좋아하는 사용자",
    "3번 (로컬/현지인)": "관광지보다 현지인들의 생활감과 로컬 분위기를 경험하고 싶은 사용자",
    "4번 (청량/애니메이션/바다)": "청량한 바다 풍경과 애니메이션 같은 분위기를 좋아하는 사용자",
    "5번 (아기자기/소박)": "아기자기하고 소박한 분위기를 좋아하는 사용자"
}


# ==================================================
# 4. 장소 설명문 생성 함수
# ==================================================
# CSV 한 행(row)을 받아서 장소 설명문 하나를 생성합니다.

def make_place_description(row):
    city = row["city"]                  # 도시명
    place_name = row["place_name"]      # 장소명

    # top1, top2 라벨 가져오기
    top1_label = row["top1_label"]
    top2_label = row["top2_label"]

    # top1, top2 비율 가져오기
    top1_ratio = row["top1_ratio"]
    top2_ratio = row["top2_ratio"]

    # 라벨명을 자연스러운 분위기 문장으로 변환
    top1_text = label_phrases.get(top1_label, top1_label)
    top2_text = label_phrases.get(top2_label, top2_label)

    # top1 라벨을 기준으로 추천 대상 문장 생성
    target_text = target_phrases.get(
        top1_label,
        "취향에 맞는 장소를 찾는 사용자"
    )

    # 최종 장소 설명문 생성
    description = (
        f"{place_name}은/는 {city}에 위치한 장소로, "
        f"{top1_text}이 가장 두드러지며 약 {top1_ratio}%의 적합도를 보인다. "
        f"또한 {top2_text}도 약 {top2_ratio}%로 함께 나타나는 장소이다. "
        f"{target_text}에게 적합하다."
    )

    return description

# ==================================================
# 5. 모든 장소에 대해 설명문 생성
# ==================================================
# apply()는 데이터프레임의 각 행마다 make_place_description 함수를 적용합니다.

df["place_description"] = df.apply(make_place_description, axis=1)


# ==================================================
# 6. 결과 저장
# ==================================================
# KR-SBERT 추천 단계에서는 이 place_descriptions.csv 파일을 사용하게 됩니다.

df.to_csv("place_descriptions.csv", index=False, encoding="utf-8-sig")


# ==================================================
# 7. 결과 확인
# ==================================================
# 생성된 장소 설명문 일부를 터미널에서 확인합니다.

print(df[["city", "place_name", "top1_label", "top1_ratio", "top2_label", "top2_ratio", "place_description"]])